// Runs the built generator through the real Prisma CLI. Needs `pnpm build` first (`pnpm test` and
// `task test` do that) and gofmt on PATH.
import { execFileSync } from 'node:child_process';
import { existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { beforeAll, describe, expect, it } from 'vitest';

const root = fileURLToPath(new URL('..', import.meta.url));
const out = join(root, 'test/e2e/out');

function prismaGenerate(): string {
  return execFileSync(join(root, 'node_modules/.bin/prisma'), ['generate', '--schema', 'test/e2e/schema'], { cwd: root, encoding: 'utf8' });
}

/** Every .go file below out/<name>, by its path from there. */
const goFiles = (name: string): string[] =>
  readdirSync(join(out, name), { recursive: true, encoding: 'utf8' })
    .filter((file) => file.endsWith('.go'))
    .map((file) => file.replaceAll('\\', '/'))
    .sort();

beforeAll(() => {
  rmSync(out, { recursive: true, force: true });
  // splitperfile writes below a module it does not create: its inputs find this go.mod by walking up.
  mkdirSync(join(out, 'splitperfile'), { recursive: true });
  writeFileSync(join(out, 'splitperfile/go.mod'), 'module example.com/e2e/splitperfile\n\ngo 1.27\n');
  prismaGenerate();
});

describe.each([
  ['defaults', ['models.go']],
  ['custom', ['content.go', 'enums.go', 'inputs.go', 'users.go']],
  ['permodel', ['enums.go', 'inputs.go', 'membership.go', 'post.go', 'profile.go', 'tag.go', 'user_accounts.go']],
  ['splitsingle', ['inputs/models.go', 'models.go']],
  [
    'splitperfile',
    ['db/content.go', 'db/enums.go', 'db/query/inputs/content.go', 'db/query/inputs/inputs.go', 'db/query/inputs/users.go', 'db/users.go'],
  ],
  [
    'splitpermodel',
    [
      'enums.go',
      'inputs/membership.go',
      'inputs/post.go',
      'inputs/profile.go',
      'inputs/tag.go',
      'inputs/user_accounts.go',
      'membership.go',
      'post.go',
      'profile.go',
      'tag.go',
      'user_accounts.go',
    ],
  ],
])('prisma generate: %s', (name, files) => {
  it('writes exactly the expected files', () => {
    expect(goFiles(name)).toEqual(files);
  });

  it.each(files)('%s matches the expected output', async (file) => {
    await expect(readFileSync(join(out, name, file), 'utf8')).toMatchFileSnapshot(`e2e/expected/${name}/${file}`);
  });

  it('is already gofmt-formatted', () => {
    expect(execFileSync('gofmt', ['-l', join(out, name)], { encoding: 'utf8' })).toBe('');
  });

  it('gets a go.mod', () => {
    expect(readFileSync(join(out, name, 'go.mod'), 'utf8')).toBe(`module example.com/e2e/${name}\n\ngo 1.27\n`);
  });
});

describe('prisma generate: post-generation steps', () => {
  const dir = join(out, 'poststeps');

  it('runGoGenerate runs the go:generate directives', () => {
    expect(existsSync(join(dir, 'Role.generated'))).toBe(true);
    expect(existsSync(join(dir, 'FDLStatus.generated'))).toBe(true);
  });

  it('removes enumer output for enums that no longer exist', () => {
    writeFileSync(join(dir, 'ghost_enumer.go'), '// Code generated by "enumer -type=Ghost"; DO NOT EDIT.\n\npackage poststeps\n');
    writeFileSync(join(dir, 'mine_enumer.go'), 'package poststeps\n');

    prismaGenerate();

    expect(existsSync(join(dir, 'ghost_enumer.go'))).toBe(false);
    expect(existsSync(join(dir, 'mine_enumer.go'))).toBe(true);
    rmSync(join(dir, 'mine_enumer.go'));
  });
});

describe('prisma generate: inputs in their own package', () => {
  it('refers to the models package by its package name and imports it only where it is used', () => {
    const single = readFileSync(join(out, 'splitsingle/inputs/models.go'), 'utf8');
    expect(single).toContain('package inputs\n');
    expect(single).toContain('\t"example.com/e2e/splitsingle"\n');
    expect(single).toMatch(/Role\s+\*Filter\[store\.Role\]/);

    // The import path comes from the go.mod above the output directory.
    const users = readFileSync(join(out, 'splitperfile/db/query/inputs/users.go'), 'utf8');
    expect(users).toContain('package query\n');
    expect(users).toContain('\t"example.com/e2e/splitperfile/db"\n');
    expect(readFileSync(join(out, 'splitperfile/db/query/inputs/content.go'), 'utf8')).not.toContain('example.com');
  });

  it('leaves no input type in the models package', () => {
    for (const file of ['splitsingle/models.go', 'splitperfile/db/users.go', 'splitpermodel/user_accounts.go']) {
      const source = readFileSync(join(out, file), 'utf8');
      expect(source).not.toContain('// Inputs');
      expect(source).not.toMatch(/Input struct|Filter\[/);
    }
  });
});

describe('prisma generate: second run', () => {
  it('prunes the inputs directory like the models directory', () => {
    const dir = join(out, 'splitpermodel/inputs');
    writeFileSync(join(dir, 'deleted_model.go'), '// Code generated by prisma-go-generator. DO NOT EDIT.\npackage inputs\n');
    writeFileSync(join(dir, 'handwritten.go'), 'package inputs\n');

    prismaGenerate();

    expect(existsSync(join(dir, 'deleted_model.go'))).toBe(false);
    expect(existsSync(join(dir, 'handwritten.go'))).toBe(true);
    expect(existsSync(join(dir, 'tag.go'))).toBe(true);
    rmSync(join(dir, 'handwritten.go'));
  });

  it('removes its own stale files and leaves everything else alone', () => {
    const dir = join(out, 'permodel');
    writeFileSync(join(dir, 'deleted_model.go'), '// Code generated by prisma-go-generator. DO NOT EDIT.\npackage permodel\n');
    writeFileSync(join(dir, 'handwritten.go'), 'package permodel\n');
    writeFileSync(join(dir, 'go.mod'), 'module example.com/e2e/permodel\n\ngo 1.27\n\n// edited by hand\n');

    prismaGenerate();

    expect(existsSync(join(dir, 'deleted_model.go'))).toBe(false);
    expect(existsSync(join(dir, 'handwritten.go'))).toBe(true);
    expect(readFileSync(join(dir, 'go.mod'), 'utf8')).toContain('// edited by hand');
    rmSync(join(dir, 'handwritten.go'));
  });
});
