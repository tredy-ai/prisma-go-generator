import type { DMMF } from '@prisma/generator-helper';
import { describe, expect, it } from 'vitest';
import { render } from '../src/layout.js';
import { config, field, fixture } from './helpers.js';

function model(name: string, fields: DMMF.Field[], extra: Partial<DMMF.Model> = {}): DMMF.Datamodel {
  return {
    enums: [],
    types: [],
    indexes: [],
    models: [{ name, dbName: null, fields, uniqueFields: [], uniqueIndexes: [], primaryKey: null, ...extra }],
  } as unknown as DMMF.Datamodel;
}

// The first six cases are prisma2go's generator_test.go, with the old yaml config translated.
describe('render: prisma2go parity', () => {
  it('basic schema with enums and relations', () => {
    const out = render(fixture('basic'), config());
    for (const want of [
      'package models',
      '// Code generated by prisma-go-generator. DO NOT EDIT.',
      '//go:generate enumer -type=Role -json -sql -text -trimprefix=Role',
      'type Role int',
      'RoleAdmin Role = iota',
      'RoleUser',
      'type User struct',
      'type Post struct',
      '// User represents the users table.',
      '// Index: User_email_key (email)',
      'Id int32 `json:"id,omitempty" db:"id"` // primary key',
      'Email string `json:"email" db:"email"`',
      'Name *string `json:"name,omitempty" db:"name"`',
      'CreatedAt time.Time `json:"createdAt,omitempty" db:"created_at"`',
      'AuthorId int32 `json:"authorId" db:"author_id"`',
      '// Relations (not persisted, populate manually)',
      'Posts []Post `json:"posts,omitempty" db:"-"`',
      'Author *User `json:"author,omitempty" db:"-"`',
      'import (\n\t"time"\n)',
    ]) {
      expect(out).toContain(want);
    }
  });

  it('complex schema with UUIDs and multiple enums', () => {
    const out = render(fixture('complex'), config());
    for (const want of [
      'type Status int',
      'type Priority int',
      'StatusDraft Status = iota',
      'PriorityLow Priority = iota',
      'Id uuid.UUID',
      'Settings json.RawMessage',
      'Id int64',
      'Tags []string',
      'Priority *Priority',
      '// Organization - An organization that owns projects',
      '// Index: unique (organizationId, name)',
      'import (\n\t"encoding/json"\n\t"github.com/google/uuid"\n\t"time"\n)',
    ]) {
      expect(out).toContain(want);
    }
  });

  it('no json tags', () => {
    const out = render(fixture('basic'), config({ structTags: ['db'] }));
    expect(out).not.toContain('json:"');
    expect(out).toContain('Email string `db:"email"`');
  });

  it('no db tags', () => {
    const out = render(fixture('basic'), config({ structTags: ['json'] }));
    expect(out).not.toContain('db:"');
    expect(out).toContain('Email string `json:"email"`');
  });

  it('no tags at all', () => {
    const out = render(fixture('basic'), config({ structTags: [] }));
    expect(out).not.toContain('`');
    expect(out).toContain('\tEmail string\n');
  });

  it('uuid as string when overridden', () => {
    const out = render(fixture('complex'), config({ types: ['db.Uuid=string'] }));
    expect(out).not.toContain('uuid.UUID');
    expect(out).not.toContain('github.com/google/uuid');
  });

  it('keeps every line of a multi-line doc comment inside a comment', () => {
    const out = render(
      model(
        'departments',
        [field({ name: 'id', type: 'Int', isId: true, documentation: 'Primary identifier.\nNever reused.' })],
        { documentation: 'Replaces the former chain.\nA department is always a flat child\nand owns exactly one workspace.' },
      ),
      config(),
    );
    expect(out).toContain(
      '// Departments - Replaces the former chain.\n// A department is always a flat child\n// and owns exactly one workspace.\ntype Departments struct {',
    );
    expect(out).toContain('\t// Primary identifier.\n\t// Never reused.\n\tId int32');
  });

  it('lists a named unique index and its field group, as prisma2go does', () => {
    const out = render(
      model('T', [field({ name: 'a' }), field({ name: 'b' })], {
        uniqueFields: [['a', 'b']],
        uniqueIndexes: [{ name: 'a_b', fields: ['a', 'b'] }],
      }),
      config(),
    );
    expect(out).toContain('// T represents the T table.\n// Index: a_b (a, b)\n// Index: unique (a, b)\ntype T struct');
  });

  it('omits the import block when nothing is imported', () => {
    expect(render(model('T', [field({ name: 'a' })]), config())).not.toContain('import');
  });
});

describe('render: options', () => {
  it('enumType = string emits typed string constants holding the database value', () => {
    const dm = fixture('basic');
    const mapped = { ...dm, enums: [{ name: 'Role', dbName: null, values: [{ name: 'ADMIN', dbName: null }, { name: 'SUPER_USER', dbName: 'super' }] }] };
    const out = render(mapped as unknown as DMMF.Datamodel, config({ enumType: 'string' }));
    expect(out).toContain('type Role string');
    expect(out).toContain('RoleAdmin Role = "ADMIN"');
    expect(out).toContain('RoleSuperUser Role = "super"');
    expect(out).not.toContain('go:generate');
    expect(out).not.toContain('iota');
  });

  it('enumType picks the integer type behind iota enums', () => {
    const out = render(fixture('basic'), config({ enumType: 'uint8' }));
    expect(out).toContain('type Role uint8\n\nconst (\n\tRoleAdmin Role = iota\n\tRoleUser\n)');
    expect(out).toContain('//go:generate enumer -type=Role');
  });

  it('enumDirective replaces or removes the go:generate line', () => {
    expect(render(fixture('basic'), config({ enumDirective: '' }))).not.toContain('go:generate');
    expect(render(fixture('basic'), config({ enumDirective: 'stringer -type={name}' }))).toContain(
      '//go:generate stringer -type=Role\ntype Role int',
    );
  });

  it('relations = false leaves relation fields out', () => {
    const out = render(fixture('basic'), config({ relations: 'false' }));
    expect(out).not.toContain('[]Post');
    expect(out).not.toContain('Relations');
    expect(out).toContain('AuthorId int32');
  });

  it('tableNameMethod adds a TableName method per model', () => {
    const out = render(fixture('basic'), config({ tableNameMethod: 'true' }));
    expect(out).toContain('func (User) TableName() string { return "users" }');
    expect(out).toContain('func (Post) TableName() string { return "Post" }');
  });

  it('initialisms rename fields but not tags', () => {
    const out = render(fixture('basic'), config({ initialisms: ['ID'] }));
    expect(out).toContain('ID int32 `json:"id,omitempty" db:"id"` // primary key');
    expect(out).toContain('AuthorID int32 `json:"authorId" db:"author_id"`');
  });

  it('omitempty = [] keeps omitempty only on relations', () => {
    const out = render(fixture('basic'), config({ omitempty: [] }));
    expect(out).toContain('Name *string `json:"name" db:"name"`');
    expect(out).toContain('Posts []Post `json:"posts,omitempty" db:"-"`');
  });

  it('structTags supports extra tags and per-tag naming', () => {
    const out = render(fixture('basic'), config({ structTags: ['json:snake', 'db', 'yaml:camel', 'bson:column'], omitempty: ['json', 'yaml'] }));
    expect(out).toContain('CreatedAt time.Time `json:"created_at,omitempty" db:"created_at" yaml:"createdAt,omitempty" bson:"created_at"`');
    expect(out).toContain('Author *User `json:"author,omitempty" db:"-" yaml:"author,omitempty" bson:"-"`');
  });

  it('refuses to emit two fields with the same Go name', () => {
    expect(() => render(model('T', [field({ name: 'user_id' }), field({ name: 'userId' })]), config())).toThrow(
      /T: fields "user_id" and "userId" both become UserId/,
    );
  });

  it('refuses to emit two types with the same Go name', () => {
    const dm = fixture('basic');
    const clash = { ...dm, enums: [{ name: 'user', dbName: null, values: [{ name: 'A', dbName: null }] }] };
    expect(() => render(clash as unknown as DMMF.Datamodel, config())).toThrow(/User/);
  });
});
