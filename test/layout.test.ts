import { describe, expect, it } from 'vitest';
import { generateFiles, goFileName } from '../src/layout.js';
import { config, fixture } from './helpers.js';

describe('generateFiles', () => {
  it('single: everything in one file, inputs after the models', () => {
    const files = generateFiles(fixture('basic'), config({ inputs: 'all' }));
    expect([...files.keys()]).toEqual(['models.go']);
    const out = files.get('models.go')!;
    expect(out.indexOf('// Enums')).toBeLessThan(out.indexOf('// Models'));
    expect(out.indexOf('// Models')).toBeLessThan(out.indexOf('// Inputs'));
    expect(out.indexOf('type Filter[T any] struct')).toBeLessThan(out.indexOf('type UserWhereInput struct'));
  });

  it('single: fileName renames the file', () => {
    expect([...generateFiles(fixture('basic'), config({ fileName: 'schema.go' })).keys()]).toEqual(['schema.go']);
  });

  it('perModel: a file per model holding its struct and its inputs, enums and shared inputs apart', () => {
    const files = generateFiles(fixture('basic'), config({ emitPerModel: 'true', inputs: 'all' }));
    expect([...files.keys()].sort()).toEqual(['enums.go', 'inputs.go', 'post.go', 'user.go']);

    const user = files.get('user.go')!;
    expect(user).toContain('type User struct {');
    expect(user).toContain('type UserWhereInput struct {');
    expect(user).not.toContain('type Post struct {');
    expect(user).not.toContain('type Role int');
    expect(user).toContain('import (\n\t"time"\n)');

    expect(files.get('post.go')).not.toContain('import');
    expect(files.get('enums.go')).toContain('type Role int');
    expect(files.get('inputs.go')).toContain('type Filter[T any] struct {');
    expect(files.get('inputs.go')).not.toContain('WhereInput struct');
  });

  it('perModel: no inputs.go unless inputs are on', () => {
    expect([...generateFiles(fixture('basic'), config({ emitPerModel: 'true' })).keys()].sort()).toEqual(['enums.go', 'post.go', 'user.go']);
  });

  it('perFile: declarations follow their .prisma file, unknown ones go to fileName', () => {
    const sources = new Map([
      ['User', 'users'],
      ['Role', 'users'],
    ]);
    const files = generateFiles(fixture('basic'), config({ emitPerFile: 'true' }), sources);
    expect([...files.keys()].sort()).toEqual(['models.go', 'users.go']);
    expect(files.get('users.go')).toContain('type Role int');
    expect(files.get('users.go')).toContain('type User struct {');
    expect(files.get('models.go')).toContain('type Post struct {');
  });

  describe('inputsOutDir', () => {
    const split = (overrides: Record<string, string | string[]> = {}, sources?: Map<string, string>) =>
      generateFiles(fixture('basic'), config({ inputs: 'all', inputsOutDir: 'inputs', ...overrides }), sources, 'example.com/app/models');

    it('single: fileName in each directory, models in one and every input in the other', () => {
      const files = split();
      expect([...files.keys()]).toEqual(['models.go', 'inputs/models.go']);
      expect(files.get('models.go')).toContain('type User struct {');
      expect(files.get('models.go')).not.toContain('// Inputs');
      expect(files.get('models.go')).toEqual(generateFiles(fixture('basic'), config()).get('models.go'));

      const inputs = files.get('inputs/models.go')!;
      expect(inputs.startsWith('// Code generated by prisma-go-generator. DO NOT EDIT.\npackage inputs\n')).toBe(true);
      expect(inputs).not.toContain('// Models');
      expect(inputs.indexOf('type Filter[T any] struct')).toBeLessThan(inputs.indexOf('type UserWhereInput struct'));
    });

    it('perModel: a file per model in each directory, shared inputs in inputs.go', () => {
      const files = split({ emitPerModel: 'true' });
      expect([...files.keys()].sort()).toEqual(['enums.go', 'inputs/inputs.go', 'inputs/post.go', 'inputs/user.go', 'post.go', 'user.go']);
      expect(files.get('user.go')).not.toContain('WhereInput');
      expect(files.get('inputs/user.go')).toContain('type UserWhereInput struct {');
      expect(files.get('inputs/user.go')).not.toContain('type User struct {');
      expect(files.get('inputs/inputs.go')).toContain('type Filter[T any] struct {');
    });

    it('perFile: a file per .prisma file in each directory', () => {
      const sources = new Map([
        ['User', 'users'],
        ['Role', 'users'],
      ]);
      const files = split({ emitPerFile: 'true' }, sources);
      expect([...files.keys()].sort()).toEqual(['inputs/inputs.go', 'inputs/models.go', 'inputs/users.go', 'models.go', 'users.go']);
      expect(files.get('inputs/users.go')).toContain('type UserWhereInput struct {');
      expect(files.get('inputs/models.go')).toContain('type PostWhereInput struct {');
    });

    it('qualifies types of the models package and imports it only where one is used', () => {
      const files = split({ emitPerModel: 'true', package: 'store', inputsOutDir: 'query/inputs', inputsPackage: 'query' });
      const user = files.get('query/inputs/user.go')!;
      expect(user.startsWith('// Code generated by prisma-go-generator. DO NOT EDIT.\npackage query\n')).toBe(true);
      expect(user).toContain('import (\n\t"example.com/app/models"\n\t"time"\n)');
      expect(user).toContain('Role *Filter[store.Role] `json:"role,omitempty"`');
      expect(user).toContain('Role store.Role `json:"role"`');
      expect(user).toContain('Role *FieldUpdate[store.Role] `json:"role,omitempty"`');
      // Relation fields name input types, which live in this package.
      expect(user).toContain('Posts *PostListRelationFilter `json:"posts,omitempty"`');
      // Post has no enum column, so its inputs do not import the models package.
      expect(files.get('query/inputs/post.go')).not.toContain('example.com/app/models');
      // The models never refer to the inputs.
      expect(files.get('user.go')).not.toContain('example.com');
    });

    it.each(['basic', 'complex'] as const)('%s: the inputs are those of the models package, with its types qualified', (name) => {
      const together = generateFiles(fixture(name), config({ inputs: 'all', package: 'zzmodels' })).get('models.go')!;
      const apart = generateFiles(fixture(name), config({ inputs: 'all', package: 'zzmodels', inputsOutDir: 'inputs' }), undefined, 'example.com/zz').get(
        'inputs/models.go',
      )!;
      const inputs = (source: string): string => source.slice(source.indexOf('// Inputs'));
      expect(apart).toContain('zzmodels.');
      expect(inputs(apart).replaceAll('zzmodels.', '')).toBe(inputs(together));
    });

    it('writes no file that would be empty', () => {
      // whereUnique has no shared types, and Post has nothing to include once relations are off.
      const files = split({ emitPerModel: 'true', inputs: ['include'], relations: 'false' });
      expect([...files.keys()].sort()).toEqual(['enums.go', 'post.go', 'user.go']);
      expect([...split({ emitPerModel: 'true', inputs: ['whereUnique'] }).keys()].sort()).toEqual([
        'enums.go',
        'inputs/post.go',
        'inputs/user.go',
        'post.go',
        'user.go',
      ]);
    });

    it('writes nothing there while inputs is empty', () => {
      expect([...generateFiles(fixture('basic'), config({ inputsOutDir: 'inputs' })).keys()]).toEqual(['models.go']);
    });

    it('needs the import path of the models package', () => {
      expect(() => generateFiles(fixture('basic'), config({ inputs: 'all', inputsOutDir: 'inputs' }))).toThrow(/import path of the models package/);
    });

    it('lets a model share a name with an input type, which is refused in one package', () => {
      const renamed = JSON.parse(JSON.stringify(fixture('basic')).replaceAll('"Post"', '"Filter"')) as Parameters<typeof generateFiles>[0];
      expect(() => generateFiles(renamed, config({ inputs: 'all' }))).toThrow(/both become the Go type Filter/);
      expect(generateFiles(renamed, config({ inputs: 'all', inputsOutDir: 'inputs' }), undefined, 'example.com/app/models').has('inputs/models.go')).toBe(true);
    });
  });

  it('every file starts with the generated-code header and the package clause', () => {
    for (const source of generateFiles(fixture('basic'), config({ emitPerModel: 'true' })).values()) {
      expect(source.startsWith('// Code generated by prisma-go-generator. DO NOT EDIT.\npackage models\n')).toBe(true);
    }
  });
});

describe('goFileName', () => {
  it.each([
    ['users', 'users.go'],
    ['Billing-Plans', 'billing_plans.go'],
    ['_private', 'private.go'],
    ['user_windows', 'user_windows_gen.go'],
    ['api_test', 'api_test_gen.go'],
    ['node_arm64', 'node_arm64_gen.go'],
    ['', 'models.go'],
  ])('%s -> %s', (stem, expected) => {
    expect(goFileName(stem)).toBe(expected);
  });
});
