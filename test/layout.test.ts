import { describe, expect, it } from 'vitest';
import { generateFiles, goFileName } from '../src/layout.js';
import { config, fixture } from './helpers.js';

describe('generateFiles', () => {
  it('single: everything in one file, inputs after the models', () => {
    const files = generateFiles(fixture('basic'), config({ inputs: 'all' }));
    expect([...files.keys()]).toEqual(['models.go']);
    const out = files.get('models.go')!;
    expect(out.indexOf('// Enums')).toBeLessThan(out.indexOf('// Models'));
    expect(out.indexOf('// Models')).toBeLessThan(out.indexOf('// Inputs'));
    expect(out.indexOf('type Filter[T any] struct')).toBeLessThan(out.indexOf('type UserWhereInput struct'));
  });

  it('single: fileName renames the file', () => {
    expect([...generateFiles(fixture('basic'), config({ fileName: 'schema.go' })).keys()]).toEqual(['schema.go']);
  });

  it('perModel: a file per model holding its struct and its inputs, enums and shared inputs apart', () => {
    const files = generateFiles(fixture('basic'), config({ emitPerModel: 'true', inputs: 'all' }));
    expect([...files.keys()].sort()).toEqual(['enums.go', 'inputs.go', 'post.go', 'user.go']);

    const user = files.get('user.go')!;
    expect(user).toContain('type User struct {');
    expect(user).toContain('type UserWhereInput struct {');
    expect(user).not.toContain('type Post struct {');
    expect(user).not.toContain('type Role int');
    expect(user).toContain('import (\n\t"time"\n)');

    expect(files.get('post.go')).not.toContain('import');
    expect(files.get('enums.go')).toContain('type Role int');
    expect(files.get('inputs.go')).toContain('type Filter[T any] struct {');
    expect(files.get('inputs.go')).not.toContain('WhereInput struct');
  });

  it('perModel: no inputs.go unless inputs are on', () => {
    expect([...generateFiles(fixture('basic'), config({ emitPerModel: 'true' })).keys()].sort()).toEqual(['enums.go', 'post.go', 'user.go']);
  });

  it('perFile: declarations follow their .prisma file, unknown ones go to fileName', () => {
    const sources = new Map([
      ['User', 'users'],
      ['Role', 'users'],
    ]);
    const files = generateFiles(fixture('basic'), config({ emitPerFile: 'true' }), sources);
    expect([...files.keys()].sort()).toEqual(['models.go', 'users.go']);
    expect(files.get('users.go')).toContain('type Role int');
    expect(files.get('users.go')).toContain('type User struct {');
    expect(files.get('models.go')).toContain('type Post struct {');
  });

  it('every file starts with the generated-code header and the package clause', () => {
    for (const source of generateFiles(fixture('basic'), config({ emitPerModel: 'true' })).values()) {
      expect(source.startsWith('// Code generated by prisma-go-generator. DO NOT EDIT.\npackage models\n')).toBe(true);
    }
  });
});

describe('goFileName', () => {
  it.each([
    ['users', 'users.go'],
    ['Billing-Plans', 'billing_plans.go'],
    ['_private', 'private.go'],
    ['user_windows', 'user_windows_gen.go'],
    ['api_test', 'api_test_gen.go'],
    ['node_arm64', 'node_arm64_gen.go'],
    ['', 'models.go'],
  ])('%s -> %s', (stem, expected) => {
    expect(goFileName(stem)).toBe(expected);
  });
});
