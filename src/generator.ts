import { spawnSync } from 'node:child_process';
import { existsSync, mkdirSync, readFileSync, readdirSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { basename, dirname, extname, join, posix, relative, sep } from 'node:path';
import type { GeneratorOptions } from '@prisma/generator-helper';
import { parseConfig, type Config } from './config.js';
import { HEADER, fileFor, generateFiles } from './layout.js';
import { toPascalCase } from './naming.js';

const fail = (message: string): Error => new Error(`prisma-go-generator: ${message}`);
// Prisma reads the generator's stderr as its RPC channel, so messages for the user go to stdout.
const warn = (message: string): void => console.log(`prisma-go-generator: warning: ${message}`);

function prismaFiles(path: string): string[] {
  if (statSync(path).isFile()) return [path];
  return readdirSync(path, { withFileTypes: true })
    .flatMap((entry) => {
      const full = join(path, entry.name);
      if (entry.isDirectory()) return prismaFiles(full);
      return entry.isFile() && entry.name.endsWith('.prisma') ? [full] : [];
    })
    .sort();
}

/**
 * Maps every model and enum to the name of the .prisma file that declares it. DMMF does not carry
 * this, so the schema files are scanned for their `model X {` and `enum X {` lines.
 */
export function declarationFiles(schemaPath: string): Map<string, string> {
  const sources = new Map<string, string>();
  for (const file of prismaFiles(schemaPath)) {
    const stem = basename(file, extname(file));
    for (const match of readFileSync(file, 'utf8').matchAll(/^[ \t]*(?:model|enum|view)\s+(\w+)\s*\{/gm)) {
      sources.set(match[1] ?? '', stem);
    }
  }
  return sources;
}

function gofmt(source: string, fileName: string): string {
  const result = spawnSync('gofmt', { input: source, encoding: 'utf8', maxBuffer: Infinity });
  if (result.error) {
    throw fail(`could not run gofmt (${result.error.message}). Install Go, or set gofmt = "false" to write unformatted code.`);
  }
  if (result.status !== 0) throw fail(`gofmt rejected ${fileName}:\n${result.stderr}`);
  return result.stdout;
}

const firstLine = (path: string): string => readFileSync(path, 'utf8').split('\n', 1)[0] ?? '';

/**
 * Deletes what an earlier run wrote and this run did not: files carrying this generator's header,
 * and enumer output for enums that no longer exist. Anything else in the directory is left alone.
 */
function prune(dir: string, written: ReadonlySet<string>, enumerFiles: ReadonlySet<string> | null): void {
  for (const name of readdirSync(dir)) {
    if (!name.endsWith('.go') || written.has(name)) continue;
    const path = join(dir, name);
    const head = firstLine(path);
    const staleEnumer = enumerFiles !== null && name.endsWith('_enumer.go') && !enumerFiles.has(name) && head.startsWith('// Code generated by "enumer');
    if (head === HEADER || staleEnumer) rmSync(path);
  }
}

function writeGoMod(cfg: Config): void {
  const path = join(cfg.dir, 'go.mod');
  // go.mod belongs to the user once it exists: `go mod tidy` adds their requirements to it.
  if (existsSync(path)) return;
  let version = cfg.goVersion;
  if (version === '') {
    const result = spawnSync('go', ['env', 'GOVERSION'], { encoding: 'utf8' });
    version = /^go(\d+\.\d+)/.exec(result.stdout ?? '')?.[1] ?? '';
    if (version === '') throw fail('generateGoMod could not ask `go env GOVERSION` for a Go version; set goVersion = "1.xx"');
  }
  writeFileSync(path, `module ${cfg.goModule}\n\ngo ${version}\n`);
}

/**
 * The Go import path of the output directory, which the inputs need once they are a package of
 * their own. A go.mod already in the directory decides; failing that the one generateGoMod is
 * about to write there, then the nearest go.mod above, then goModule taken at its word.
 */
export function modelsImportPath(cfg: Pick<Config, 'dir' | 'generateGoMod' | 'goModule'>): string {
  if (cfg.generateGoMod && !existsSync(join(cfg.dir, 'go.mod'))) return cfg.goModule;
  for (let dir = cfg.dir; ; dir = dirname(dir)) {
    const goMod = join(dir, 'go.mod');
    if (existsSync(goMod)) {
      const module = /^module\s+"?([^\s"]+)"?/m.exec(readFileSync(goMod, 'utf8'))?.[1];
      if (!module) throw fail(`${goMod} has no module line, so inputsOutDir cannot work out an import path for the models package`);
      return [module, ...relative(dir, cfg.dir).split(sep).filter(Boolean)].join('/');
    }
    if (dirname(dir) === dir) break;
  }
  if (cfg.goModule !== '') return cfg.goModule;
  throw fail(
    `inputsOutDir needs the import path of the models package, and there is no go.mod in ${cfg.dir} or above it. ` +
      'Run `go mod init` there, or set goModule = "<import path of the output directory>".',
  );
}

const enumerOutput = (goName: string): string => `${goName.toLowerCase()}_enumer.go`;

function runEnumer(cfg: Config, enums: [goName: string, file: string][]): void {
  for (const [goName, file] of enums) {
    const args = [`-type=${goName}`, ...cfg.enumerArgs.map((arg) => arg.replaceAll('{name}', goName))];
    const output = enumerOutput(goName);
    // Naming the source file keeps this working in a directory that is not inside a Go module.
    const result = spawnSync('enumer', [...args, `-output=${output}`, file], { cwd: cfg.dir, encoding: 'utf8' });
    if (result.error) {
      warn('enumer is not on PATH, so no enum methods were generated. Install it with `go install github.com/dmarkham/enumer@latest`, or set enumer = "false".');
      return;
    }
    if (result.status !== 0) {
      warn(`enumer failed for ${goName}:\n${result.stderr}${result.stdout}`);
      continue;
    }
    // enumer records its command line in the file's first line. Write the line the go:generate
    // directive would produce, so this run and a later `go generate` leave identical files.
    const path = join(cfg.dir, output);
    const lines = readFileSync(path, 'utf8').split('\n');
    if (lines[0]?.startsWith('// Code generated by "enumer ')) {
      lines[0] = `// Code generated by "enumer ${args.join(' ')}"; DO NOT EDIT.`;
      writeFileSync(path, lines.join('\n'));
    }
  }
}

export function generate(options: GeneratorOptions): void {
  const cfg = parseConfig(options.generator);
  cfg.warnings.forEach(warn);
  const { datamodel } = options.dmmf;
  const sources = cfg.layout === 'perFile' ? declarationFiles(options.schemaPath) : new Map<string, string>();
  const split = cfg.inputsOutDir !== '' && cfg.inputs.length > 0;
  const files = generateFiles(datamodel, cfg, sources, split ? modelsImportPath(cfg) : '');

  // A file is named by its path below the output directory: the inputs' own directory, if any, is the only one below it.
  const written = new Map<string, Set<string>>([[cfg.dir, new Set()]]);
  mkdirSync(cfg.dir, { recursive: true });
  for (const [name, source] of files) {
    const dir = name.includes('/') ? join(cfg.dir, posix.dirname(name)) : cfg.dir;
    mkdirSync(dir, { recursive: true });
    writeFileSync(join(cfg.dir, name), cfg.gofmt ? gofmt(source, name) : source);
    written.set(dir, (written.get(dir) ?? new Set()).add(posix.basename(name)));
  }

  const enums = datamodel.enums.map((e): [string, string] => [toPascalCase(e.name, cfg.initialisms), fileFor('enum', e.name, cfg, sources)]);
  prune(cfg.dir, written.get(cfg.dir) ?? new Set(), cfg.enumer ? new Set(enums.map(([goName]) => enumerOutput(goName))) : null);
  // The inputs' directory is pruned even when nothing was written to it, so turning inputs off cleans it up.
  const inputsDir = cfg.inputsOutDir === '' ? '' : join(cfg.dir, cfg.inputsOutDir);
  if (inputsDir !== '' && existsSync(inputsDir)) prune(inputsDir, written.get(inputsDir) ?? new Set(), null);

  if (cfg.generateGoMod) writeGoMod(cfg);
  if (cfg.enumer) runEnumer(cfg, enums);
  if (cfg.runGoGenerate) {
    for (const dir of written.keys()) {
      const result = spawnSync('go', ['generate', '.'], { cwd: dir, encoding: 'utf8' });
      if (result.error) throw fail(`runGoGenerate could not run go (${result.error.message})`);
      if (result.status !== 0) throw fail(`go generate failed:\n${result.stderr}${result.stdout}`);
    }
  }
}
