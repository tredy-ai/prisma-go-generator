import type { DMMF } from '@prisma/generator-helper';
import type { Config } from './config.js';
import { modelInputNames, modelInputs, sharedInputNames, sharedInputs } from './inputs.js';
import { toPascalCase, toSnakeCase } from './naming.js';
import { renderEnum, renderModel } from './render.js';

/** First line of every file this generator writes; pruning only deletes files that start with it. */
export const HEADER = '// Code generated by prisma-go-generator. DO NOT EDIT.';

// A trailing _test, _<GOOS> or _<GOARCH> in a file name is a build constraint to the go tool.
const CONSTRAINT_SUFFIXES = new Set(
  (
    'test aix android darwin dragonfly freebsd hurd illumos ios js linux nacl netbsd openbsd plan9 solaris wasip1 windows zos ' +
    '386 amd64 amd64p32 arm arm64 arm64be armbe loong64 mips mips64 mips64le mips64p32 mips64p32le mipsle ppc ppc64 ppc64le ' +
    'riscv riscv64 s390 s390x sparc sparc64 wasm'
  ).split(' '),
);

/** Turns a model or schema-file name into a Go file name that the go tool always compiles. */
export function goFileName(stem: string): string {
  let base = stem
    .toLowerCase()
    .replaceAll(/[^a-z0-9_]+/g, '_')
    .replace(/^_+/, '');
  if (base === '') base = 'models';
  if (CONSTRAINT_SUFFIXES.has(base.split('_').pop() ?? '')) base += '_gen';
  return `${base}.go`;
}

/**
 * The file a model or enum is written to. `sources` maps Prisma declaration names to the name of
 * the .prisma file they come from, and is only needed for the per-file layout.
 */
export function fileFor(kind: 'enum' | 'model', name: string, cfg: Config, sources: ReadonlyMap<string, string>): string {
  if (cfg.layout === 'perModel') return kind === 'enum' ? 'enums.go' : goFileName(toSnakeCase(name));
  if (cfg.layout === 'perFile') {
    const source = sources.get(name);
    return source === undefined ? cfg.fileName : goFileName(source);
  }
  return cfg.fileName;
}

interface FileParts {
  imports: Set<string>;
  enums: string[];
  models: string[];
  inputs: string[];
}

function assemble(pkg: string, parts: FileParts): string {
  const imports = [...parts.imports].sort();
  const blocks = [
    `${HEADER}\npackage ${pkg}`,
    ...(imports.length > 0 ? [`import (\n${imports.map((path) => `\t"${path}"`).join('\n')}\n)`] : []),
    ...(parts.enums.length > 0 ? ['// Enums', ...parts.enums] : []),
    ...(parts.models.length > 0 ? ['// Models', ...parts.models] : []),
    ...(parts.inputs.length > 0 ? ['// Inputs', ...parts.inputs] : []),
  ];
  return `${blocks.join('\n\n')}\n`;
}

function checkTypeNames(datamodel: DMMF.Datamodel, cfg: Config): void {
  const taken = new Map<string, string>();
  const claim = (goName: string, owner: string): void => {
    const other = taken.get(goName);
    if (other !== undefined) throw new Error(`prisma-go-generator: ${other} and ${owner} both become the Go type ${goName}`);
    taken.set(goName, owner);
  };
  for (const e of datamodel.enums) claim(toPascalCase(e.name, cfg.initialisms), `enum ${e.name}`);
  for (const m of datamodel.models) claim(toPascalCase(m.name, cfg.initialisms), `model ${m.name}`);
  if (cfg.inputs.length === 0) return;
  for (const name of sharedInputNames(cfg)) claim(name, 'the shared input types');
  for (const m of datamodel.models) {
    for (const name of modelInputNames(m, cfg)) claim(name, `the inputs of model ${m.name}`);
  }
}

/** Renders the whole datamodel: Go file name -> unformatted Go source. */
export function generateFiles(datamodel: DMMF.Datamodel, cfg: Config, sources: ReadonlyMap<string, string> = new Map()): Map<string, string> {
  checkTypeNames(datamodel, cfg);

  const files = new Map<string, FileParts>();
  const file = (name: string): FileParts => {
    let parts = files.get(name);
    if (!parts) files.set(name, (parts = { imports: new Set(), enums: [], models: [], inputs: [] }));
    return parts;
  };
  if (cfg.layout === 'single') file(cfg.fileName);

  for (const e of datamodel.enums) file(fileFor('enum', e.name, cfg, sources)).enums.push(renderEnum(e, cfg));

  const withInputs = cfg.inputs.length > 0 && datamodel.models.length > 0;
  if (withInputs) file(cfg.layout === 'single' ? cfg.fileName : 'inputs.go').inputs.push(...sharedInputs(cfg));

  for (const m of datamodel.models) {
    const parts = file(fileFor('model', m.name, cfg, sources));
    const model = renderModel(m, cfg);
    parts.models.push(model.code);
    model.imports.forEach((path) => parts.imports.add(path));
    if (!withInputs) continue;
    for (const input of modelInputs(m, cfg)) {
      parts.inputs.push(input.code);
      input.imports.forEach((path) => parts.imports.add(path));
    }
  }

  return new Map([...files].map(([name, parts]) => [name, assemble(cfg.package, parts)]));
}

/** The single-file layout's one file. */
export function render(datamodel: DMMF.Datamodel, cfg: Config): string {
  return generateFiles(datamodel, cfg).get(cfg.fileName) ?? '';
}
